package com.enol.salesforze.data.location

import android.content.Context
import android.content.pm.PackageManager
import android.location.Location
import android.os.Build
import android.provider.Settings
import com.enol.salesforze.data.local.AppDatabase
import com.enol.salesforze.data.local.entities.PendingSyncQueueEntity
import com.enol.salesforze.data.remote.session.SessionManager
import org.json.JSONObject
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone
import java.util.UUID

/**
 * Enterprise Anti-Cheat & GPS Spoofing Detection Engine.
 * Detects mock providers, simulated GPS apps, and invalid sensor telemetry
 * to prevent unauthorized check-ins and false distance claims.
 */
object AntiSpoofingDetector {

    /**
     * Common known Mock GPS & Fake Location application package identifiers.
     */
    private val KNOWN_FAKE_GPS_PACKAGES = listOf(
        "com.lexa.fakegps",
        "com.rosteam.gpsemulator",
        "com.incorporateapps.fakegps.fre",
        "com.incorporateapps.fakegps",
        "com.fakegps.mock",
        "org.hola.gpslocation",
        "com.location.changer",
        "com.mock.location",
        "com.divi.fakeGPS",
        "com.app.fakegps",
        "com.blogspot.newapphorizons.fakegps",
        "com.usefullapps.dennisch旅館.fakegps",
        "com.ninja.gps"
    )

    /**
     * Validates whether a provided [Location] was generated by a mock provider,
     * developer options simulation, or third-party GPS spoofing tool.
     */
    fun isMockLocation(context: Context, location: Location): Boolean {
        // 1. API 31+ (Android 12+) native mock detection
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            if (location.isMock) return true
        }

        // 2. API 18-30 mock provider detection
        @Suppress("DEPRECATION")
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.JELLY_BEAN_MR2) {
            if (location.isFromMockProvider) return true
        }

        // 3. Provider name sanity check
        val provider = location.provider?.lowercase(Locale.ROOT)
        if (provider != null && (provider.contains("mock") || provider.contains("spoof"))) {
            return true
        }

        // 4. Secure Settings mock location enabled check (fallback for older environments)
        try {
            @Suppress("DEPRECATION")
            val allowMock = Settings.Secure.getString(
                context.contentResolver,
                Settings.Secure.ALLOW_MOCK_LOCATION
            )
            if (allowMock != null && allowMock != "0") {
                return true
            }
        } catch (_: Exception) {
            // Ignore security permission restrictions on newer Android versions
        }

        // 5. Package scan for notorious fake GPS applications
        if (hasFakeGpsAppInstalled(context)) {
            return true
        }

        // 6. Impossible telemetry check: exact 0.0 accuracy or non-zero speed with completely zero altitude variation
        if (location.hasAccuracy() && location.accuracy <= 0.0001f) {
            return true
        }

        return false
    }

    /**
     * Scans installed application packages on the device to detect presence of Fake GPS tools.
     */
    fun hasFakeGpsAppInstalled(context: Context): Boolean {
        val pm = context.packageManager
        for (pkg in KNOWN_FAKE_GPS_PACKAGES) {
            try {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
                    pm.getPackageInfo(pkg, PackageManager.PackageInfoFlags.of(0))
                } else {
                    @Suppress("DEPRECATION")
                    pm.getPackageInfo(pkg, 0)
                }
                return true
            } catch (_: PackageManager.NameNotFoundException) {
                // Not installed, continue scanning
            } catch (_: Exception) {
                // SecurityException or query limitation
            }
        }
        return false
    }

    /**
     * Logs a high-priority security violation record locally in Room for urgent manager alerting,
     * and flags the current session to block check-ins, visits, and order creation.
     */
    suspend fun logSecurityAlert(
        context: Context,
        location: Location,
        database: AppDatabase,
        sessionManager: SessionManager,
        detectedReason: String = "MOCK_GPS_DETECTED"
    ) {
        val userId = sessionManager.getCachedUserId() ?: "UNKNOWN_USER"
        val nowIso = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss.SSS'Z'", Locale.US).apply {
            timeZone = TimeZone.getTimeZone("UTC")
        }.format(Date())

        val alertPayload = JSONObject().apply {
            put("event", "SECURITY_MOCK_GPS_DETECTED")
            put("user_id", userId)
            put("timestamp", nowIso)
            put("latitude", location.latitude)
            put("longitude", location.longitude)
            put("accuracy", if (location.hasAccuracy()) location.accuracy else -1f)
            put("speed", if (location.hasSpeed()) location.speed else -1f)
            put("provider", location.provider ?: "UNKNOWN")
            put("reason", detectedReason)
            put("device_model", Build.MODEL)
            put("android_version", Build.VERSION.RELEASE)
        }.toString()

        val alertEntity = PendingSyncQueueEntity(
            id = UUID.randomUUID().toString(),
            entityType = "security.mock_gps_detected",
            entityId = UUID.randomUUID().toString(),
            action = "SECURITY_ALERT",
            payloadJson = alertPayload,
            idempotencyKey = "sec_${userId}_${System.currentTimeMillis()}",
            attemptCount = 0,
            lastAttemptAt = null,
            errorMessage = null,
            createdAt = nowIso
        )

        // 1. Persist security alert in pending sync queue for immediate server upload
        database.pendingSyncQueueDao().insertSyncItem(alertEntity)

        // 2. Lock session state to block sales rep check-ins and order booking
        sessionManager.flagMockLocationBlocked(true)
    }
}
